function filteredProducts() {
  const q = filterState.q.trim().toLowerCase();
  return PRODUCTS.filter(p =>
    (filterState.cat === "all" || p.cat === filterState.cat) &&
    (!q || p.name.toLowerCase().includes(q) || p.desc.toLowerCase().includes(q) || CAT_TITLE[p.cat].toLowerCase().includes(q)) &&
    (filterState.min == null || p.price >= filterState.min) &&
    (filterState.max == null || p.price <= filterState.max)
  );
}
